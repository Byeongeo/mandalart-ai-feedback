type ConcernRule = {
  kind: RuleConcernKind;
  /** 걱정 표현(예외 구절을 가린 글에 하나라도 있으면 걸림) */
  patterns: readonly RegExp[];
  /** 검사 전에 □로 가리는, 걱정 표현이 아닌 것으로 알려진 구절 */
  benign?: RegExp;
  /** 걸렸어도 칸 전체가 이 모양이면 넘김 */
  skipCell?: (t: string) => boolean;
};

// 종류별 표현. 앞에 있는 종류가 먼저입니다(한 칸에 둘 이상 걸리면 앞 종류).
export const CONCERN_RULES: readonly ConcernRule[] = [
  { kind: "self_harm", patterns: SELF_HARM, benign: SELF_HARM_BENIGN },
  { kind: "abuse", patterns: ABUSE, benign: ABUSE_BENIGN },
  { kind: "bullying", patterns: BULLYING, benign: BULLYING_BENIGN, skipCell: helpingOthers },
  { kind: "violence", patterns: VIOLENCE, benign: VIOLENCE_BENIGN },
  { kind: "eating", patterns: EATING, benign: EATING_BENIGN },
];

// 검사용으로 다듬은 글: 공백·문장부호·기호·이모지, 'ㅠㅜ' 같은 모음 자모와 'ㅋㅎ', 한글 채움 문자를 지웁니다.
// 'ㅈㄱㅅㄷ' 같은 자음 줄임말은 남깁니다.
const NOISE = new RegExp("[\\s\\p{P}\\p{S}\\p{Z}\\p{Cf}\\p{M}\\u3164\\u115F\\u1160\\uFFA0\\u314F-\\u3163ㅋㅎ]", "gu");
export function compactText(s: string): string {
  return s.normalize("NFC").replace(NOISE, "");
}

function ruleMatches(rule: ConcernRule, t: string): boolean {
  const s = rule.benign ? t.replace(rule.benign, "□") : t;
  if (!rule.patterns.some((p) => p.test(s))) return false;
  return !rule.skipCell?.(s);
}

/** 글 한 칸에서 걸리는 종류(없으면 null) */
export function matchConcernText(text: string): RuleConcernKind | null {
  const t = compactText(text);
  if (!t) return null;
  for (const rule of CONCERN_RULES) if (ruleMatches(rule, t)) return rule.kind;
  return null;
}

export type RuleConcern = { kind: RuleConcernKind; cells: Target[] };

// 걸린 칸마다 종류(중심 → 세부 → 실천 칸 순서)
function ruleConcernHits(c: MandalartContent): { kind: RuleConcernKind; cell: Target }[] {
  const hits: { kind: RuleConcernKind; cell: Target }[] = [];
  const check = (text: string, cell: Target) => {
    const kind = matchConcernText(text);
    if (kind) hits.push({ kind, cell });
  };
  check(c.goal, { kind: "goal" });
  c.subs.forEach((s, i) => check(s, { kind: "sub", sub: i }));
  c.actions.forEach((row, i) => row.forEach((a, j) => check(a, { kind: "action", sub: i, action: j })));
  return hits;
}

/**
 * 만다라트 전체 검사. 걸린 칸들(종류와 상관없이 모두)과, 그중 가장 앞 순위 종류를 돌려줍니다(없으면 null).
 * 교사 화면은 cells로 '어느 칸'인지 보여 줄 수 있습니다(칸 글 자체는 교사 화면의 만다라트에 이미 있음).
 */
export function ruleConcern(c: MandalartContent): RuleConcern | null {
  const hits = ruleConcernHits(c);
  if (!hits.length) return null;
  const order = CONCERN_RULES.map((r) => r.kind);
  const kind = hits.map((h) => h.kind).sort((a, b) => order.indexOf(a) - order.indexOf(b))[0];
  return { kind, cells: hits.map((h) => h.cell) };
}

/** 만다라트에서 걸린 종류마다 그 종류의 칸들(앞 순위 종류부터, 걸린 종류만). 교사 화면이 종류별로 칸을 나눠 보여 줄 때 씁니다. */
export function ruleConcernsByKind(c: MandalartContent): RuleConcern[] {
  const hits = ruleConcernHits(c);
  return CONCERN_RULES.map((r) => ({ kind: r.kind, cells: hits.filter((h) => h.kind === r.kind).map((h) => h.cell) }))
    .filter((g) => g.cells.length > 0);
}
